from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path

from network_sampling.matsim_network import (
    MatsimLink,
    MatsimNetwork,
    load_matsim_network,
)
from network_sampling.street_segments import (
    StreetSegment,
    StreetSegmentIndex,
)


# ---------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------

DEFAULT_WIDTH_ATTRIBUTE = "width"


# A link containing only these modes can reasonably represent
# bicycle-only infrastructure.
BIKE_ONLY_MODES = frozenset(
    {
        "bike",
        "bike_loop",
    }
)

# Artificial public-transport links may have no physical road width.
ARTIFICIAL_MODE = "artificial"

# ---------------------------------------------------------------------
# Missing-width classification
# ---------------------------------------------------------------------


def get_highway_type(
    link: MatsimLink,
) -> str | None:
    """
    Return the MATSim link's highway type, if any.
    """

    return link.attributes.get("osm:way:highway")

def is_bike_only_link(
    link: MatsimLink,
) -> bool:
    """
    Return True when the link only permits bicycle modes.
    """

    modes = link.allowed_modes

    return (
        bool(modes)
        and modes.issubset(BIKE_ONLY_MODES)
    )


def is_artificial_link(
    link: MatsimLink,
) -> bool:
    """
    Return True when the MATSim link is marked as artificial.

    Artificial links are generated by the network/PT processing
    pipeline and do not necessarily correspond to a physical road.
    Therefore, missing physical width is acceptable for these links.
    """

    return ARTIFICIAL_MODE in link.allowed_modes


def classify_missing_width_segment(
    segment: StreetSegment,
    network: MatsimNetwork,
    width_attribute: str,
) -> str:
    """
    Classify why a StreetSegment has no complete width information.

    Returns one of:
        bike_only
        artificial_pt
        partial_width
        unexplained
    """

    links = [
        network.links[link_id]
        for link_id in segment.link_ids
    ]

    
    # -------------------------------------------------------------
    # Acceptable reason 1:
    # all links are bicycle-only.
    # -------------------------------------------------------------

    if all(
        is_bike_only_link(link)
        for link in links
    ):
        return "bike_only"

    # -------------------------------------------------------------
    # Acceptable reason 2:
    # all links are artificial PT-only links.
    # -------------------------------------------------------------

    if all(
        is_artificial_link(link)
        for link in links
    ):
        return "artificial_pt"

    # -------------------------------------------------------------
    # Check whether some, but not all, links have width.
    #
    # This is useful because StreetSegment.total_width_m becomes None
    # whenever even one constituent directional link has no width.
    # -------------------------------------------------------------

    has_width = [
        link.attributes.get(width_attribute) is not None
        for link in links
    ]

    if any(has_width) and not all(has_width):
        return "partial_width"

    return "unexplained"


# ---------------------------------------------------------------------
# Printing helpers
# ---------------------------------------------------------------------

def print_header(
    title: str,
) -> None:
    print()
    print(title)
    print("-" * len(title))


def format_modes(
    link: MatsimLink,
) -> str:
    return ",".join(
        sorted(link.allowed_modes)
    )


def describe_segment(
    segment: StreetSegment,
    network: MatsimNetwork,
    width_attribute: str,
) -> None:
    """
    Print detailed information for one street segment.
    """

    print()
    print(f"Segment: {segment.id}")
    print(
        f"  Nodes:       "
        f"{segment.node_a} <-> {segment.node_b}"
    )
    print(
        f"  Length:      "
        f"{segment.length_m:.2f} m"
    )
    print(
        f"  Total width: "
        f"{segment.total_width_m}"
    )
    print(
        f"  OSM way:     "
        f"{segment.osm_way_id}"
    )
    print(
        f"  Links:       "
        f"{segment.link_ids}"
    )

    for link_id in segment.link_ids:

        link = network.links[link_id]

        highway = get_highway_type(link)

        width = link.attributes.get(
            width_attribute
        )

        print(
            "    "
            f"{link.id}: "
            f"{link.from_node}->{link.to_node}, "
            f"modes=[{format_modes(link)}], "
            f"highway={highway}, "
            f"width={width}"
        )


# ---------------------------------------------------------------------
# Main inspection
# ---------------------------------------------------------------------

def inspect_network(
    network_path: Path,
    width_attribute: str,
    max_examples: int,
) -> None:

    # -------------------------------------------------------------
    # Load baseline MATSim network
    # -------------------------------------------------------------

    network = load_matsim_network(
        network_path
    )

    print_header("MATSim network")

    print(
        f"File:  {network_path}"
    )
    print(
        f"Nodes: {len(network.nodes):,}"
    )
    print(
        f"Links: {len(network.links):,}"
    )

    # -------------------------------------------------------------
    # Link-level mode overview
    # -------------------------------------------------------------

    mode_counts = Counter()

    for link in network.links.values():

        for mode in link.allowed_modes:
            mode_counts[mode] += 1

    print_header("MATSim link modes")

    for mode, count in sorted(
        mode_counts.items()
    ):
        print(
            f"{mode:25s} {count:8,d}"
        )

    # -------------------------------------------------------------
    # Build physical street segments
    # -------------------------------------------------------------

    segment_index = (
        StreetSegmentIndex.from_network(
            network,
            width_attribute=width_attribute,
        )
    )

    segments = segment_index.all()

    print_header("Physical street segments")

    print(
        f"Segments: {len(segments):,}"
    )

    # -------------------------------------------------------------
    # MATSim links per segment
    # -------------------------------------------------------------

    links_per_segment = Counter(
        segment.number_of_links
        for segment in segments
    )

    print()
    print("MATSim links per segment:")

    for number_of_links, count in sorted(
        links_per_segment.items()
    ):
        print(
            f"  {number_of_links:2d} link(s): "
            f"{count:8,d} segments"
        )

    # -------------------------------------------------------------
    # Directionality
    # -------------------------------------------------------------

    bidirectional = 0
    one_direction = 0

    for segment in segments:

        if segment_index.is_bidirectional(
            segment.id
        ):
            bidirectional += 1
        else:
            one_direction += 1

    print()
    print(
        f"Bidirectional segments: "
        f"{bidirectional:,}"
    )
    print(
        f"One-direction segments: "
        f"{one_direction:,}"
    )

    # -------------------------------------------------------------
    # Physical length
    # -------------------------------------------------------------

    total_length_km = (
        sum(
            segment.length_m
            for segment in segments
        )
        / 1000.0
    )

    print()
    print(
        f"Physical street length: "
        f"{total_length_km:.2f} km"
    )

    # -------------------------------------------------------------
    # Width availability
    # -------------------------------------------------------------

    segments_with_width = [
        segment
        for segment in segments
        if segment.total_width_m is not None
    ]

    segments_without_width = [
        segment
        for segment in segments
        if segment.total_width_m is None
    ]

    print_header("Street segment width coverage")

    print(
        f"Width attribute: "
        f"'{width_attribute}'"
    )

    print(
        f"Segments with width:    "
        f"{len(segments_with_width):8,d}"
    )

    print(
        f"Segments without width: "
        f"{len(segments_without_width):8,d}"
    )

    if segments:

        coverage = (
            100.0
            * len(segments_with_width)
            / len(segments)
        )

        print(
            f"Width coverage:         "
            f"{coverage:8.2f}%"
        )

    # -------------------------------------------------------------
    # Classify missing widths
    # -------------------------------------------------------------

    missing_width_classes: Counter[str] = (
        Counter()
    )

    classified_segments: dict[
        str,
        list[StreetSegment],
    ] = {}

    for segment in segments_without_width:

        classification = (
            classify_missing_width_segment(
                segment=segment,
                network=network,
                width_attribute=width_attribute,
            )
        )

        missing_width_classes[
            classification
        ] += 1

        classified_segments.setdefault(
            classification,
            [],
        ).append(segment)

    print_header(
        "Missing width classification"
    )

    labels = {
        "bike_only":
            "Bike-only link",
        "artificial_pt":
            "Artificial PT-only link",
        "partial_width":
            "Only some directional links have width",
        "unexplained":
            "Unexplained missing width",
    }

    for classification in (
        "bike_only",
        "artificial_pt",
        "partial_width",
        "unexplained",
    ):

        count = missing_width_classes.get(
            classification,
            0,
        )

        print(
            f"{labels[classification]:45s}"
            f"{count:8,d}"
        )

    acceptable_missing = (
        missing_width_classes.get(
            "bike_only",
            0,
        )
        +
        missing_width_classes.get(
            "artificial_pt",
            0,
        )
    )

    problematic_missing = (
        missing_width_classes.get(
            "partial_width",
            0,
        )
        +
        missing_width_classes.get(
            "unexplained",
            0,
        )
    )

    print()
    print(
        f"Acceptable missing widths: "
        f"{acceptable_missing:,}"
    )

    print(
        f"Potentially problematic:   "
        f"{problematic_missing:,}"
    )

    # -------------------------------------------------------------
    # Width statistics
    # -------------------------------------------------------------

    widths = [
        segment.total_width_m
        for segment in segments_with_width
        if segment.total_width_m is not None
    ]

    if widths:

        print_header("Street width statistics")

        print(
            f"Minimum: "
            f"{min(widths):.2f} m"
        )

        print(
            f"Maximum: "
            f"{max(widths):.2f} m"
        )

        sorted_widths = sorted(widths)

        middle = len(sorted_widths) // 2

        if len(sorted_widths) % 2:
            median_width = (
                sorted_widths[middle]
            )
        else:
            median_width = (
                sorted_widths[middle - 1]
                + sorted_widths[middle]
            ) / 2.0

        print(
            f"Median:  "
            f"{median_width:.2f} m"
        )

    # -------------------------------------------------------------
    # Segments with unusual number of MATSim links
    # -------------------------------------------------------------

    unusual_segments = [
        segment
        for segment in segments
        if segment.number_of_links > 2
    ]

    print_header(
        "Segments with more than two MATSim links"
    )

    print(
        f"Count: {len(unusual_segments):,}"
    )

    for segment in unusual_segments[
        :max_examples
    ]:

        describe_segment(
            segment=segment,
            network=network,
            width_attribute=width_attribute,
        )

    if (
        len(unusual_segments)
        > max_examples
    ):
        print()
        print(
            f"... {len(unusual_segments) - max_examples:,} "
            f"additional segments not shown."
        )

    # -------------------------------------------------------------
    # Partial width examples
    # -------------------------------------------------------------

    partial_width_segments = (
        classified_segments.get(
            "partial_width",
            [],
        )
    )

    if partial_width_segments:

        print_header(
            "Segments with partial width information"
        )

        print(
            f"Count: "
            f"{len(partial_width_segments):,}"
        )

        for segment in partial_width_segments[
            :max_examples
        ]:

            describe_segment(
                segment=segment,
                network=network,
                width_attribute=width_attribute,
            )

        if (
            len(partial_width_segments)
            > max_examples
        ):
            print()
            print(
                f"... "
                f"{len(partial_width_segments) - max_examples:,} "
                f"additional segments not shown."
            )

    # -------------------------------------------------------------
    # Unexplained missing widths
    # -------------------------------------------------------------

    unexplained_segments = (
        classified_segments.get(
            "unexplained",
            [],
        )
    )

    print_header(
        "Unexplained missing widths"
    )

    print(
        f"Count: "
        f"{len(unexplained_segments):,}"
    )

    if not unexplained_segments:

        print(
            "All missing widths can be explained by "
            "bike-only/PT-only links."
        )

    else:

        for segment in unexplained_segments[
            :max_examples
        ]:

            describe_segment(
                segment=segment,
                network=network,
                width_attribute=width_attribute,
            )

        if (
            len(unexplained_segments)
            > max_examples
        ):
            print()
            print(
                f"... "
                f"{len(unexplained_segments) - max_examples:,} "
                f"additional segments not shown."
            )

    # -------------------------------------------------------------
    # Final summary
    # -------------------------------------------------------------

    print_header("Summary")

    print(
        f"MATSim links:                 "
        f"{len(network.links):,}"
    )

    print(
        f"Physical street segments:     "
        f"{len(segments):,}"
    )

    print(
        f"Physical street length:       "
        f"{total_length_km:.2f} km"
    )

    print(
        f"Segments with width:          "
        f"{len(segments_with_width):,}"
    )

    print(
        f"Acceptable missing widths:    "
        f"{acceptable_missing:,}"
    )

    print(
        f"Problematic missing widths:   "
        f"{problematic_missing:,}"
    )


# ---------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------

def parse_args() -> argparse.Namespace:

    parser = argparse.ArgumentParser(
        description=(
            "Inspect a MATSim baseline network and its "
            "derived physical street segments."
        )
    )

    parser.add_argument(
        "network",
        type=Path,
        help=(
            "MATSim network file (.xml or .xml.gz)."
        ),
    )

    parser.add_argument(
        "--width-attribute",
        default=DEFAULT_WIDTH_ATTRIBUTE,
        help=(
            "MATSim link attribute containing directional "
            "road width. "
            f"Default: {DEFAULT_WIDTH_ATTRIBUTE}"
        ),
    )

    parser.add_argument(
        "--max-examples",
        type=int,
        default=20,
        help=(
            "Maximum number of problematic segments "
            "printed per category. Default: 20"
        ),
    )

    return parser.parse_args()


def main() -> None:

    args = parse_args()

    inspect_network(
        network_path=args.network,
        width_attribute=args.width_attribute,
        max_examples=args.max_examples,
    )


if __name__ == "__main__":
    main()